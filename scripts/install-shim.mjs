#!/usr/bin/env node
// Writes a stable entry point ~/.claude/agy/agy-companion.mjs that forwards to this plugin copy,
// so agents/skills can call the companion without knowing where the plugin is installed.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const real = path.join(path.dirname(fileURLToPath(import.meta.url)), 'agy-companion.mjs');
const dir = process.env.AGY_STATE_DIR || path.join(os.homedir(), '.claude', 'agy');
fs.mkdirSync(dir, { recursive: true });
const shim = path.join(dir, 'agy-companion.mjs');
const body = '// generated by the agy plugin (scripts/install-shim.mjs) — do not edit\n'
  + 'process.argv[1] = ' + JSON.stringify(real) + ';\n'
  + 'await import(' + JSON.stringify(pathToFileURL(real).href) + ');\n';
let cur = ''; try { cur = fs.readFileSync(shim, 'utf8'); } catch {}
if (cur !== body) fs.writeFileSync(shim, body);

// Same for the team MCP server, and register it with agy once (agy reads ~/.gemini/config/mcp_config.json).
const realMcp = path.join(path.dirname(real), 'team-mcp.mjs');
const mcpShim = path.join(dir, 'team-mcp.mjs');
const mcpBody = '// generated by the agy plugin (scripts/install-shim.mjs) — do not edit\n'
  + 'await import(' + JSON.stringify(pathToFileURL(realMcp).href) + ');\n';
let curMcp = ''; try { curMcp = fs.readFileSync(mcpShim, 'utf8'); } catch {}
if (curMcp !== mcpBody) fs.writeFileSync(mcpShim, mcpBody);
if (!process.env.AGY_SKIP_MCP_REGISTER) {
  const cfgFile = path.join(os.homedir(), '.gemini', 'config', 'mcp_config.json');
  let has = false;
  try { has = !!JSON.parse(fs.readFileSync(cfgFile, 'utf8'))?.mcpServers?.['claude-team']; } catch {}
  if (!has) {
    const { spawnSync } = await import('node:child_process');
    spawnSync(process.env.AGY_BIN || 'agy', ['mcp', 'add', 'claude-team', process.execPath, mcpShim], { stdio: 'ignore', windowsHide: true, timeout: 20000 });
  }
}
